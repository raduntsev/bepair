/*
  Courses are content, not data: they live here, typed, and the database keeps
  only what each person did with them (supabase/migrations/0015). A new course
  is one more entry in COURSES — the screens, progress, privacy, reminders and
  the journal pick it up without any other change.

  A lesson is a sequence of fields. Every field has an id that is stable inside
  its lesson: answers are stored as { [field id]: value } per lesson, so a
  wording can be improved later without losing what people already wrote.

  Lessons are walked in order. A lesson opens once the one before it is marked
  done; nothing inside a lesson is required — the course itself says the
  answers are a «programme maximum», and a blank field must never block a step.
*/

/* Every field may be marked optional («по желанию»); all others must be answered before the step is done. */
interface FieldBase {
  id: string;
  q: string;
  hint?: string;
  optional?: boolean;
}

export type Field =
  /* Free text. */
  | (FieldBase & { kind: 'text'; rows?: number; echo?: Echo[] })
  /* A fixed number of short lines: «Я — …» ten times. `ordered` numbers them. Every line must be filled. */
  | (FieldBase & { kind: 'list'; count: number; prefix?: string; ordered?: boolean })
  /* A 0–10 score for each item, e.g. the spheres of life. Every item must be scored. */
  | (FieldBase & { kind: 'scale'; items: string[]; min: number; max: number })
  /* Rows of columns that grow on demand: the growth-mindset table, behavioural activation. One full row is enough. */
  | (FieldBase & { kind: 'table'; columns: string[]; rows: number; max?: number; example?: string[] })
  /* The thought diary from the journal, shown inside the lesson. One entry is enough. */
  | (FieldBase & { kind: 'diary' });

/*
  What to read before answering, as a sequence of blocks so the page has a
  rhythm instead of a wall of text: a lead, short paragraphs with **bold**,
  subheadings, the one key thought, a couple's story, two columns to compare,
  terms that unfold, a card to think over before opening, a small quiz with
  explanations, a «try it now», a quote. Written in the voice of a family
  psychologist; the ideas are retold from the course's own lesson notes.
*/
export type TheoryBlock =
  | { t: 'lead'; text: string }
  | { t: 'p'; text: string }
  | { t: 'h'; text: string }
  | { t: 'key'; text: string }
  | { t: 'list'; items: string[]; ordered?: boolean }
  | { t: 'terms'; items: { term: string; def: string }[] }
  | { t: 'story'; title: string; text: string }
  | { t: 'compare'; left: { title: string; items: string[] }; right: { title: string; items: string[] } }
  | { t: 'reveal'; prompt: string; answer: string }
  | { t: 'quiz'; q: string; options: { text: string; ok?: boolean; why: string }[] }
  | { t: 'try'; text: string }
  | { t: 'quote'; text: string; source: string };

export interface Theory {
  /* Minutes to read, shown under the heading. */
  minutes: number;
  blocks: TheoryBlock[];
  read?: { label: string; href: string }[];
}

/* An earlier answer shown beside a question, so a final reflection can compare. */
export interface Echo {
  lesson: string;
  field: string;
  label: string;
}

export type FieldValue = string | string[] | string[][] | Record<string, number>;
export type LessonAnswers = Record<string, FieldValue>;

export interface Lesson {
  id: string;
  /* As the course numbers it: «1.3». */
  code: string;
  title: string;
  kind: 'lesson' | 'practice' | 'final';
  /* A short frame for the questions, so they stand without the video. */
  intro?: string;
  theory?: Theory;
  fields: Field[];
  links?: { label: string; href: string }[];
  /* A closing note after the fields. */
  tip?: string;
  /* Something for the two of you, once both have done the step. */
  together?: string;
}

/* The badge a finished module earns. The icon is a key, drawn by the app (lib stays free of React). */
export type BadgeIcon = 'gem' | 'mountain' | 'brain' | 'compass' | 'waves' | 'shield' | 'route' | 'award';

export interface Module {
  id: string;
  n: number;
  title: string;
  about: string;
  badge: { name: string; icon: BadgeIcon };
  lessons: Lesson[];
}

export interface Course {
  id: string;
  title: string;
  /* The language the content is written in; the app's chrome follows the reader. */
  lang: 'ru' | 'en';
  about: string;
  /* How to work with it — shown once, folded afterwards. */
  guidance: string[];
  modules: Module[];
  books?: string[];
}

